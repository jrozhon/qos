        <figcaption><b>{{ r.label }}</b><br>SSIM <b>{{ r.ssim.toFixed(2) }}</b></figcaption>
        <canvas class="map" :ref="el => printCanvas(el, r.map.map(v => Math.max(0, v)), W - 10, H - 10, 255)" />
      </figure>
    </div>
    <p class="lead">All six distortions are scaled to the <b>same MSE = {{ target }}</b>, so PSNR is identical for every one
      ({{ (10 * Math.log10(255 * 255 / target)).toFixed(1) }} dB). SSIM compares mean, contrast and structure in an
      11 × 11 window around every pixel and ranks them very differently:</p>
    <ul class="why">
