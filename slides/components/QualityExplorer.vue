      </figure>
    </div>

    <div class="howto">
      <label class="slider">
        MSE (all rows)
        <input v-model.number="target" type="range" min="10" max="600" step="10">
        <span class="num">{{ target }} → PSNR {{ (10 * Math.log10(255 * 255 / target)).toFixed(1) }} dB</span>
      </label>
      <p><b>How it works.</b> The slider sets one MSE for <b>all six rows</b>: each distortion is made just strong
        enough to reach it, so <b>PSNR is the same in every row</b>. Clicking a row only chooses what is shown.</p>
      <p>SSIM compares mean, contrast and structure in an 11 × 11 window around every pixel; the <b>SSIM map</b>
        shows each window, the table their average.</p>
    </div>

    <table>
      <colgroup><col style="width: 235px"><col style="width: 55px"><col style="width: 60px"><col></colgroup>
      <thead><tr><th>Distortion</th><th>MSE</th><th>PSNR</th><th>SSIM</th></tr></thead>
      <tbody>
        <tr v-for="r in rows" :key="r.kind" :class="{ on: r.kind === selected }" @click="selected = r.kind">
          <td>{{ r.label }}<span v-if="r.capped" class="cap"> max</span><span v-else-if="r.clipped" class="cap"> clipped</span></td>
          <td class="num">{{ r.mse.toFixed(0) }}</td>
          <td class="num">{{ r.psnr.toFixed(1) }}</td>
          <td class="ssim">
            <span class="bar" :style="{ width: `${Math.max(0, r.ssim) * 70}px` }" />
            <span class="num">{{ r.ssim.toFixed(2) }}</span>
          </td>
        </tr>
      </tbody>
    </table>

    <div class="explain">
      <div class="head">{{ current?.label }} · SSIM {{ current?.ssim.toFixed(2) }}</div>
      <p><b>Strength at this MSE:</b> {{ strength }}.</p>
      <p><b>What changes:</b> {{ EXPLAIN[selected].what }}</p>
      <p><b>Why SSIM reacts this way:</b> {{ EXPLAIN[selected].why }}</p>
      <p><b>SSIM map:</b> {{ EXPLAIN[selected].map }}</p>
      <p v-if="current?.capped" class="try"><b>max</b>: full strength reached, the real MSE stays below the target.</p>
      <p v-else-if="current?.clipped" class="try"><b>clipped</b>: pixels hit black or white, so the real MSE stays below the target.</p>
    </div>
  </div>
</template>

